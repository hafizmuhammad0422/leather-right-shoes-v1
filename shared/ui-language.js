  document.addEventListener('change',event=>{if(event.target.matches('[data-ui-rename-mode]')){setRenameMode(event.target.checked);event.target.checked=renameMode;}});
  function apply(root=document){
    document.documentElement.lang=language;
    document.documentElement.dir=language==='ur'?'rtl':'ltr';
    const find=selector=>[...(root.matches?.(selector)?[root]:[]),...root.querySelectorAll(selector)];
    find('[data-ui-name]').forEach(node=>{const value=nameText(node.dataset.uiName,node.dataset.uiNameId,node.dataset.uiNameOriginal)+(node.dataset.uiNameSuffix||'');if(node.textContent!==value)node.textContent=value;node.dir='auto';});
    find('[data-i18n]').forEach(node=>{if(labelEditor?.node===node)return;let values={};try{const parsed=JSON.parse(node.dataset.i18nValues||'{}');if(parsed&&typeof parsed==='object')values=parsed;}catch{}try{const names=JSON.parse(node.dataset.uiNameValues||'{}');for(const [key,name] of Object.entries(names))if(name&&typeof name.collection==='string')values[key]=nameText(name.collection,name.id,name.original);}catch{}const value=labelText(node,values);if(node.textContent!==value)node.textContent=value;node.lang=language;});
    find('[data-i18n-placeholder]').forEach(node=>{const value=t(node.dataset.i18nPlaceholder);if(node.getAttribute('placeholder')!==value)node.setAttribute('placeholder',value);});
    find('[data-i18n-scope]').forEach(node=>{node.lang=language;node.dir=language==='ur'?'rtl':'ltr';node.style.fontFamily=language==='ur'?"'Noto Naskh Arabic', 'Segoe UI', sans-serif":'';});
    find('[data-app-language]').forEach(node=>{node.value=language;});
    find('[data-ui-rename-mode]').forEach(node=>{node.checked=renameMode;});
  }
  function setLanguage(value,persist=true){
    if(value!=='en'&&value!=='ur')return false;
    finishLabelEdit();
    if(persist){try{localStorage.setItem(storageKey,value);}catch{apply();return false;}}
    language=value;apply();window.dispatchEvent(new CustomEvent('factory-language-change',{detail:{language}}));return true;
  }
